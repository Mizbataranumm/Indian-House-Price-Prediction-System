"""PDF report export using ReportLab."""
from __future__ import annotations

import io
from typing import Any, Dict
from reportlab.lib.pagesizes import A4
from reportlab.lib import colors
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import cm
from reportlab.platypus import (
    SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, PageBreak,
)


def _fmt_inr(v: float) -> str:
    if v is None:
        return "—"
    if v >= 1e7:
        return f"INR {v/1e7:.2f} Cr"
    return f"INR {v/1e5:.2f} L"


def build_report(input_payload: Dict[str, Any], prediction: Dict[str, Any],
                 shap: Dict[str, Any], emi: Dict[str, Any] | None = None) -> bytes:
    buf = io.BytesIO()
    doc = SimpleDocTemplate(
        buf, pagesize=A4, leftMargin=2 * cm, rightMargin=2 * cm,
        topMargin=2 * cm, bottomMargin=2 * cm, title="House Price Report",
    )
    styles = getSampleStyleSheet()
    h1 = ParagraphStyle("h1", parent=styles["Title"], fontSize=20,
                        textColor=colors.HexColor("#0F172A"), spaceAfter=12)
    h2 = ParagraphStyle("h2", parent=styles["Heading2"], fontSize=14,
                        textColor=colors.HexColor("#2563EB"), spaceAfter=8)
    body = styles["BodyText"]

    story = []
    story.append(Paragraph("Indian House Price Prediction Report", h1))
    story.append(Paragraph(
        "Generated by the ML-driven Indian Real Estate Analytics Platform.", body))
    story.append(Spacer(1, 12))

    # Property details
    story.append(Paragraph("Property Details", h2))
    detail_rows = [["Field", "Value"]]
    for k in ["city", "locality", "bhk", "area_sqft", "resale", "tier"]:
        if k in input_payload:
            detail_rows.append([k.replace("_", " ").title(), str(input_payload[k])])
    # Amenities
    amen_on = [k for k in input_payload
               if k.startswith("amen_") and int(input_payload.get(k, 0)) == 1]
    if amen_on:
        detail_rows.append(["Amenities",
                            ", ".join(a.replace("amen_", "").replace("_", " ")
                                      for a in amen_on)])
    t = Table(detail_rows, hAlign="LEFT", colWidths=[6 * cm, 8 * cm])
    t.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#F1F5F9")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.HexColor("#0F172A")),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#CBD5E1")),
        ("FONTSIZE", (0, 0), (-1, -1), 9),
    ]))
    story.append(t)
    story.append(Spacer(1, 14))

    # Prediction
    story.append(Paragraph("Predicted Price", h2))
    pred_rows = [
        ["Best Model",        prediction["best_model"]],
        ["Predicted Price",   _fmt_inr(prediction["predicted_price"])],
        ["Confidence Range",  f"{_fmt_inr(prediction['confidence_low'])} – "
                              f"{_fmt_inr(prediction['confidence_high'])}"],
        ["Price / sqft",      f"INR {prediction['price_per_sqft']:.0f}"],
    ]
    t2 = Table(pred_rows, hAlign="LEFT", colWidths=[6 * cm, 8 * cm])
    t2.setStyle(TableStyle([
        ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#CBD5E1")),
        ("FONTSIZE", (0, 0), (-1, -1), 10),
        ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#F8FAFC")),
    ]))
    story.append(t2)
    story.append(Spacer(1, 14))

    # All model predictions
    story.append(Paragraph("Model Comparison (this property)", h2))
    rows = [["Model", "Predicted Price"]] + [
        [m, _fmt_inr(p)] for m, p in prediction["all_predictions"].items()
    ]
    t3 = Table(rows, hAlign="LEFT", colWidths=[7 * cm, 7 * cm])
    t3.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#0F172A")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#CBD5E1")),
        ("FONTSIZE", (0, 0), (-1, -1), 9),
    ]))
    story.append(t3)
    story.append(Spacer(1, 14))

    # SHAP top contributions
    story.append(Paragraph("SHAP – Top Feature Contributions", h2))
    rows = [["Feature", "Impact (INR)"]]
    for c in shap.get("contributions", [])[:10]:
        rows.append([c["feature"], f"{c['value']:+,.0f}"])
    t4 = Table(rows, hAlign="LEFT", colWidths=[8 * cm, 6 * cm])
    t4.setStyle(TableStyle([
        ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#CBD5E1")),
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#F1F5F9")),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, -1), 9),
    ]))
    story.append(t4)

    if emi:
        story.append(Spacer(1, 14))
        story.append(Paragraph("EMI Summary", h2))
        rows = [
            ["Loan Amount", _fmt_inr(emi["loan_amount"])],
            ["Annual Rate", f"{emi['rate']}%"],
            ["Tenure (yrs)", str(emi["tenure_years"])],
            ["Monthly EMI", _fmt_inr(emi["emi"])],
            ["Total Interest", _fmt_inr(emi["total_interest"])],
            ["Total Payable", _fmt_inr(emi["total_payment"])],
        ]
        t5 = Table(rows, hAlign="LEFT", colWidths=[6 * cm, 8 * cm])
        t5.setStyle(TableStyle([
            ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#CBD5E1")),
            ("FONTSIZE", (0, 0), (-1, -1), 10),
        ]))
        story.append(t5)

    story.append(Spacer(1, 18))
    story.append(Paragraph(
        "Estimates produced by an ensemble ML pipeline trained on a "
        "metropolitan India housing dataset. Actual market prices may "
        "vary based on micro-location, condition and timing.",
        ParagraphStyle("disc", parent=body, textColor=colors.HexColor("#64748B"),
                       fontSize=8)))
    doc.build(story)
    return buf.getvalue()
